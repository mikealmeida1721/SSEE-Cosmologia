# ═══════════════════════════════════════════════════════════════════
# §1  SSEE algebraic constants (Paper 1, zero free parameters)
# ═══════════════════════════════════════════════════════════════════
phi_  = (1 + 5**0.5) / 2       # 1.61803
pi_   = np.pi                   # 3.14159
beta_ = (phi_ + pi_) / 2        # BIAL  2.37981
Kv_   = phi_ + pi_ + pi_ + phi_ # KRYSTOS (pi_+phi_+pi_+phi_ = 2*(pi_+phi_))
# correct:
Omega_ = pi_ + phi_              # OMEGA 4.75963
Kv_    = phi_ + pi_ + Omega_    # KRYSTOS 9.51926
Tr_    = 3*(phi_ + beta_)        # TRIAL 11.99354
Mv_    = phi_ + pi_ + Kv_        # MIKAEL_V 14.27888  (decia 14.27880: errata del comentario, corregida 2026-09-19)
AURA_  = phi_ + beta_            # 3.99785
MIRA_  = AURA_ / 2               # 1.99892
BUFFER_= Mv_ - Tr_               # 2.28534  (decia 2.28526: errata del comentario, corregida 2026-09-19)

w0_     = -Tr_ / Mv_             # -0.8400
wa_     = -(Omega_ + phi_) / Kv_ # -0.6699
Om_DE   = Tr_ / Mv_              # 0.8400
Om_dyn  = BUFFER_ / Mv_          # 0.1600
Om_b    = 0.049                  # baryonic (Planck 2018)
H0_     = __import__("ssee_core").H0_GLOBAL  # H_glob, km/s/Mpc (3(φ+π)² es el blanco puro)
# ORIGEN-VALOR: 0.6796 — H_alg/100 = 3(phi+pi)^2/100 = 0.679621, a 4 decimales
h_      = H0_ / 100              # 0.6796 = H_alg/100 = 3(phi+pi)^2/100

# Bellini-Sawicki αK prediction (Paper 7, algebraic)
# ORIGEN-VALOR: 0.4032 — 3*0.840*0.160 con los valores redondeados; exacto 3*(Tr/Mv)*(1-Tr/Mv) = 0.403302
aK_alg  = 3 * Om_DE * (1 + w0_)   # at z=0: 3×0.840×0.160 = 0.4032

print("=" * 60)
print("SSEE hi_class cross-check — Paper 3")
print(f"  w₀ = {w0_:.4f}   wₐ = {wa_:.4f}")
print(f"  H₀ = {H0_:.3f} km/s/Mpc   h = {h_:.4f}")
print(f"  Ωm,dyn = {Om_dyn:.4f}   Ω_DE = {Om_DE:.4f}")
print(f"  αK (algebraic, z=0) = {aK_alg:.4f}")
print("=" * 60)

# ═══════════════════════════════════════════════════════════════════
# §2  Load Planck PR4 TT data (generated by ssee_paper3_cmb.py)
# ═══════════════════════════════════════════════════════════════════
PLANCK_TT_FILE = "data/raw/planck_pr4_TT.txt"

def load_planck_tt():
    if os.path.exists(PLANCK_TT_FILE):
        data = np.loadtxt(PLANCK_TT_FILE)
        ell, Dl, sig_up, sig_down = data[:,0], data[:,1], data[:,2], data[:,3]
        sigma = 0.5*(sig_up + sig_down)
        return ell.astype(int), Dl, sigma
    else:
        # Synthetic Planck-like spectrum for testing
        print("  [warn] Planck PR4 file not found — using synthetic reference")
        ell = np.arange(2, 2000)
        # Rough Planck-like TT spectrum
        Dl = 5765 * np.exp(-((ell-220)/60)**2) * (1 + 0.45*np.cos(np.pi*(ell-220)/280))
        Dl = np.abs(Dl) + 100
        sigma = 0.03 * Dl + 20
        return ell, Dl, sigma

ell_p, Dl_p, sig_p = load_planck_tt()
ell_use = ell_p[(ell_p >= 30) & (ell_p <= 2000)]
Dl_use  = Dl_p[(ell_p >= 30) & (ell_p <= 2000)]
sig_use = sig_p[(ell_p >= 30) & (ell_p <= 2000)]
N_TT    = len(ell_use)
print(f"\nLoaded {N_TT} TT multipoles from Planck PR4 (ℓ=30–2000)")

# ═══════════════════════════════════════════════════════════════════
# §3  Run CLASS with SSEE parameters
# ═══════════════════════════════════════════════════════════════════
def run_class(label, params_extra):
    cosmo = Class()
    params_base = {
        'h'            : h_,
        'omega_b'      : 0.02237,                # Ωb h² (Planck 2018 physical)
        'omega_cdm'    : (Om_dyn - Om_b) * h_**2,  # Ω_cdm h²  (= 0.160-0.049)*h²
        'Omega_Lambda' : 0,
        'w0_fld'       : w0_,
        'wa_fld'       : wa_,
        'n_s'          : 1 - phi_**(-7),          # 0.96556
        'A_s'          : 2.1e-9,
        'tau_reio'     : 0.054,
        'output'       : 'tCl mPk',
        'P_k_max_h/Mpc': 10.0,
        'l_max_scalars': 2500,
    }
    params_base.update(params_extra)
    cosmo.set(params_base)
    try:
        cosmo.compute()
        cls = cosmo.raw_cl(2500)
        ell_c = np.arange(0, 2501)
        # Dℓ = ℓ(ℓ+1) Cℓ / (2π) in μK²
        Dl_c = ell_c*(ell_c+1)*cls['tt'] / (2*np.pi) * (2.7255e6)**2
        # Derived params
        derived = cosmo.get_current_derived_parameters(
            ['Omega_m', 'Omega_Lambda', 'sigma8'])
        cosmo.struct_cleanup()
        return Dl_c, derived
    except Exception as e:
        cosmo.struct_cleanup()
        raise e

print("\n§3 Running CLASS — SSEE configuration...")
Dl_ssee, der_ssee = run_class("SSEE", {})
print(f"  CLASS OK   σ₈(CLASS) = {der_ssee.get('sigma8', 'N/A'):.4f}")

print("\n§3 Running CLASS — ΛCDM reference (6 free params)...")
try:
    Dl_lcdm, der_lcdm = run_class("LCDM", {
        'omega_cdm'  : 0.1200,
        'omega_b'    : 0.02237,
        'h'          : 0.6736,   # Planck 2018 (arXiv:1807.06209)
        'n_s'        : 0.9649,
        'w0_fld'     : -1.0,
        'wa_fld'     : 0.0,
    })
    print(f"  CLASS OK   σ₈(ΛCDM, CLASS) = {der_lcdm.get('sigma8', 'N/A'):.4f}")
    lcdm_ok = True
except Exception as e:
    print(f"  ΛCDM CLASS failed: {e}")
    lcdm_ok = False

# ═══════════════════════════════════════════════════════════════════
# §4  χ²_r comparison
# ═══════════════════════════════════════════════════════════════════
def interp_Dl(Dl_full, ell_target):
    ell_full = np.arange(len(Dl_full))
    valid = (ell_full >= 2) & (ell_full < len(Dl_full))
    f = interp1d(ell_full[valid], Dl_full[valid], kind='linear',
                 bounds_error=False, fill_value=0.0)
    return f(ell_target)

Dl_ssee_interp = interp_Dl(Dl_ssee, ell_use)
chi2_ssee = np.sum(((Dl_ssee_interp - Dl_use)/sig_use)**2)
chi2r_ssee = chi2_ssee / N_TT

if lcdm_ok:
    Dl_lcdm_interp = interp_Dl(Dl_lcdm, ell_use)
    chi2_lcdm = np.sum(((Dl_lcdm_interp - Dl_use)/sig_use)**2)
    chi2r_lcdm = chi2_lcdm / N_TT
    delta_chi2 = chi2_ssee - chi2_lcdm
    # ΔBIC: k_SSEE=0 (no free params), k_ΛCDM=6
    BIC_ssee = chi2_ssee + 0 * np.log(N_TT)
    BIC_lcdm = chi2_lcdm + 6 * np.log(N_TT)
    dBIC = BIC_ssee - BIC_lcdm

print("\n" + "=" * 60)
print("§4 χ²_r results (hi_class, TT ℓ=30–2000)")
