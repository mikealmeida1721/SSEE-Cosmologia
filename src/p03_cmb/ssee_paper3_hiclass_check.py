if lcdm_ok:
    print(f"  ΛCDM (k=6): χ²_r = {chi2r_lcdm:.3f}")
    print(f"  Δχ² = {delta_chi2:.1f}")
    print(f"  ΔBIC (k_SSEE=0 vs k_ΛCDM=6) = {dBIC:.1f}")

